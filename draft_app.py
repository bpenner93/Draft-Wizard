# ⚠ NOT `name.split()[-1]`. Roughly one in twenty draftable players carries a
# generational suffix, so that renders Marvin Harrison Jr. as a chip labelled
# "Jr. · WR" -- and there are three different Jr.s inside the top 80, so the
# label is not just ugly, it is ambiguous. Seen live in a mock at pick 63.
def arc_flag(p) -> str:
    """Compact signal for the board. A HIGH percentile means we are projecting
    ABOVE what comparable players actually did -- a caution, not praise.

    Reads the `arc` field baked into draft_board.json by export_draft_board.py.
    Deliberately NOT computed at runtime: the phone app is a standalone repo and
    cannot import player_history or reach data/player_history.db."""
    if p is None or (isinstance(p, float) and pd.isna(p)):
        return ""
    if p >= 85:
        return f"! {int(p)}"
    if p <= 20:
        return f"+ {int(p)}"
    return str(int(p))


def build_rookie_board(board):
    """Rookie-draft view: rookies only, valued by the REAL dynasty market
    (DynastyProcess superflex value) when available, else our dynasty value.
    Pseudo rookie-ADP = that value's rank (no public rookie-draft ADP feed)."""
    rb = []
    for p in board:
        if not p.get("rookie"):
            continue
        q = dict(p)
        q["pts"] = p.get("dp2") or p.get("dp1") or p.get("dyn") or p.get("pts") or 0.0
        q["rec"] = 0.0
        rb.append(q)
    rb.sort(key=lambda x: -x["pts"])
    for i, q in enumerate(rb, 1):
        q["adp"], q["adp_sd"], q["adp_sf"] = float(i), 3.0 + 0.12 * i, None
    return rb


def revalue_rookies(rb, superflex):
    """Re-rank the rookie board by the DynastyProcess market value that matches the
    league type -- 1QB value (dp1) for single-QB, superflex value (dp2) for SF -- and
    rebuild the pseudo rookie-ADP. In 1QB a top rookie QB (Mendoza) falls behind the
    WRs; in SF he's a premium. Mutates in place (shared with by_id)."""
    for q in rb:
        primary = q.get("dp2") if superflex else q.get("dp1")
        q["pts"] = primary or q.get("dp1") or q.get("dp2") or q.get("dyn") or q.get("pts") or 0.0
    for i, q in enumerate(sorted(rb, key=lambda x: -(x["pts"] or 0.0)), 1):
        q["adp"], q["adp_sd"], q["adp_sf"] = float(i), 3.0 + 0.12 * i, None


