def sleeper_sync(draft_id: str = None, league_id: str = None):
    """Pull picks + config (type->snake, your slot, the LIVE starting lineup) +
    board metadata (team names, traded picks) from Sleeper. Accepts a draft_id OR
    a league_id."""
    from sleeper_api import league_state
    stt = league_state(league_id=league_id, draft_id=(draft_id or "").strip() or None)
    ci = {"type": stt["type"], "snake": stt["snake"], "teams": stt["teams"],
          "rounds": stt["rounds"], "my_slot": stt["my_slot"],
          "roster_cfg": stt.get("roster_cfg") or {}, "status": stt.get("status"),
          "league_name": stt.get("league_name"), "pick_timer": stt.get("pick_timer")}
    drafted, matched, missed = [], [], []
    for pk in stt["picks"]:
        m = pk.get("metadata") or {}
        nm = f"{m.get('first_name','')} {m.get('last_name','')}".strip()
        pos = pos_norm(m.get("position"))
        if pos == "DST":                              # matched by team, never by name
            pid = dst_map.get(_team_key(m.get("team") or pk.get("player_id")))
        else:
            pid = (key_map.get((norm_name(nm), pos))
                   or fold_map.get((_fold(nm), pos)))
        if pid:
            drafted.append(pid); matched.append(pid)
        else:
            # keep the slot occupied so pick numbers / whose-turn stay aligned (e.g. IDP
            # picks our offense-only board doesn't carry)
            drafted.append(f"__off_{pk.get('pick_no')}")
            missed.append(f"{nm} ({pos})")
    ss.drafted = drafted
    ss["sleeper_cfg"] = ci
    ss["sleeper_state"] = stt
    return len(matched), missed, ci


def sleeper_pick_count(league_id=None, draft_id=None) -> int | None:
    """Just the pick COUNT -- one small GET, for the auto-sync poller. Deliberately
    separate from sleeper_sync: polling the full league_state every few seconds
    would be 5 requests a tick, and the only question is 'did anything change'."""
    import requests
    try:
        if not draft_id:
            from sleeper_api import resolve_draft_id
            draft_id = resolve_draft_id(league_id)
        r = requests.get(f"https://api.sleeper.app/v1/draft/{draft_id}/picks", timeout=8)
        r.raise_for_status()
        return len(r.json() or [])
    except Exception:
        return None          # a blip must never break the draft screen


def total_picks():
    return cfg.teams * cfg.total_rounds()


def do_pick(pid):
    """Commit a pick; in practice mode, let the AI draft the other teams up to your next pick."""
    if len(ss.drafted) >= total_picks():      # the draft has a last pick
        return
    draft_ids([pid])
    ss["last_my_pick"] = len(ss.drafted)      # where the "since your pick" feed starts
    # With auto-advance off the room does NOT jump to your next turn, so the
    # step controls have something to step: otherwise every pick lands you back
    # on the clock and "one pick" is always a no-op.
    if st.session_state.get("practice") and ss.get("auto_adv", True):
        ss.drafted = mock_advance(prep_valued(working, cfg), cfg, ss.drafted,
                                 None, seed=ss['room_seed'])


def team_roster(slot):
    """[(overall, player)] for one drafting slot, in pick order."""
    out = []
    for i, pid in enumerate(ss.drafted):
        if team_on_clock(cfg, i + 1) == slot:
            p = by_id.get(pid)
            if p:
                out.append((i + 1, p))
    return out


